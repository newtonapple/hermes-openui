// Generates src/world-path.js: Natural Earth 110m land as one compact SVG path in
// equirectangular units of 0.1 degree: x=(lon+180)*10, y=(90-lat)*10 (so 3600 x 1800).
// Run: node scripts/gen-world.mjs   (needs world-atlas + topojson-client, dev only)
import fs from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
const require = createRequire(import.meta.url);
const topo = require("world-atlas/land-110m.json");
const land = feature(topo, topo.objects.land);
const polys = land.features ? land.features.flatMap((f) => f.geometry.coordinates) : land.geometry.coordinates;
let d = "";
let pts = 0, unwrapped = 0, polar = 0;
for (const poly of polys) {
  for (const ring of poly) {
    // raw projected points (floats, 0.1 degree units)
    let raw = ring.map(([lon, lat]) => [(lon + 180) * 10, (90 - lat) * 10]);
    let q;
    if (raw.some(([, y]) => y >= 1799.5)) {
      // Polar ring (Antarctica): drop the points on the -90 line, close along the bottom edge instead.
      const keep = raw.filter(([, y]) => y < 1799.5);
      q = [...keep, [3600, 1800], [0, 1800]];
      polar++;
    } else {
      // Unwrap antimeridian jumps so the ring stays continuous; the component draws 3 copies (-3600/0/+3600).
      q = [raw[0]];
      let shift = 0;
      for (let i = 1; i < raw.length; i++) {
        const dx = raw[i][0] - raw[i - 1][0];
        if (dx > 1800) shift -= 3600; else if (dx < -1800) shift += 3600;
        q.push([raw[i][0] + shift, raw[i][1]]);
      }
      if (shift !== 0) unwrapped++;
    }
    q = q.map(([x, y]) => [Math.round(x), Math.round(y)]).filter((pt, i, a) => !i || pt[0] !== a[i - 1][0] || pt[1] !== a[i - 1][1]);
    if (q.length < 4) continue;
    d += `M${q[0][0]} ${q[0][1]}l`;
    let px = q[0][0], py = q[0][1];
    const parts = [];
    for (let i = 1; i < q.length; i++) { parts.push(q[i][0] - px, q[i][1] - py); px = q[i][0]; py = q[i][1]; }
    d += parts.join(" ").replace(/ -/g, "-") + "z";
    pts += q.length;
  }
}
console.log("antimeridian-unwrapped rings:", unwrapped, "polar rings:", polar);
fs.writeFileSync(new URL("../src/world-path.js", import.meta.url), `// generated by scripts/gen-world.mjs (Natural Earth 110m land, public domain)\nexport const WORLD_PATH = ${JSON.stringify(d)};\n`);
console.log("rings ok, points:", pts, "path chars:", d.length);

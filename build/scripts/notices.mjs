// Writes ../THIRD_PARTY_NOTICES.md from the packages the desktop bundle really contains (dist/bundled-inputs.json, written by
// plugin-build.mjs). The core and pack bundles are subsets of it. usage: node scripts/notices.mjs   (run plugin-build.mjs first)
import fs from "node:fs";
import path from "node:path";

const BUILD = path.resolve(import.meta.dirname, "..");
const inputs = JSON.parse(fs.readFileSync(path.join(BUILD, "dist/bundled-inputs.json"), "utf8"));
const PERMISSIVE = new Set(["MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "0BSD", "CC0-1.0", "BlueOak-1.0.0", "Unlicense"]);

const roots = new Map();
for (const f of inputs) {
  const i = f.lastIndexOf("node_modules/");
  if (i < 0) continue;
  const rest = f.slice(i + "node_modules/".length).split("/");
  const name = rest[0].startsWith("@") ? rest.slice(0, 2).join("/") : rest[0];
  roots.set(name, path.resolve(BUILD, f.slice(0, i), "node_modules", name));
}
const rows = [];
for (const [name, dir] of [...roots].sort((a, b) => a[0].localeCompare(b[0]))) {
  const pj = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  const license = typeof pj.license === "string" ? pj.license : pj.license?.type || (pj.licenses || []).map((l) => l.type).join(" OR ") || "UNKNOWN";
  const lic = fs.readdirSync(dir).find((f) => /^(licen[sc]e|copying)/i.test(f));
  const text = lic ? fs.readFileSync(path.join(dir, lic), "utf8") : "";
  const copyright = (text.split("\n").find((l) => /copyright/i.test(l)) || "").replace(/^[\s#*/-]+/, "").replace(/\s+/g, " ").trim();
  rows.push({ name, version: pj.version, license, copyright });
}
const odd = rows.filter((r) => !PERMISSIVE.has(r.license));
let md = "# Third-party notices\n\nThe browser runtime (`assets/*.js.gz`) and the desktop half (`desktop/plugin.js`) are bundles of the open-source packages below, " +
  "built by `build/`. This file is generated by `build/scripts/notices.mjs`; do not edit it by hand. Each package's full license text ships in its npm tarball.\n\n" +
  "Original code in this repository is MIT licensed (see `LICENSE`). The world coastline data in `build/src/world-path.js` is generated from " +
  "Natural Earth (public domain) through the `world-atlas` package at build time.\n\n| Package | Version | License | Copyright |\n|---|---|---|---|\n";
for (const r of rows) md += `| ${r.name} | ${r.version} | ${r.license} | ${r.copyright.replace(/\|/g, "/")} |\n`;
md += `\n${rows.length} packages. ` + (odd.length ? `**Review needed**, not on the permissive list: ${odd.map((r) => r.name + " (" + r.license + ")").join(", ")}.` : "Every license is on the permissive list (MIT, ISC, BSD, Apache-2.0, 0BSD, CC0, BlueOak, Unlicense); no copyleft.") + "\n";
fs.writeFileSync(path.join(BUILD, "../THIRD_PARTY_NOTICES.md"), md);
console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} packages; non-permissive: ${odd.length ? odd.map((r) => r.name + "=" + r.license).join(", ") : "none"}`);
